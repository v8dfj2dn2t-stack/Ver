def places():
    d = json.load(open(os.path.join(SC, 'ne10_places.geojson')))
    idx = {}
    for f in d['features']:
        p = f['properties']
        if p.get('ADM0NAME') != 'Russia' and p.get('SOV0NAME') != 'Russia': continue
        nm = p.get('NAME_RU')
        if not nm: continue
        c = f['geometry']['coordinates']
        cur = idx.get(nm)
        rank = 0 if p.get('FEATURECLA') in ('Admin-0 capital', 'Admin-1 capital') else 1
        if cur is None or rank < cur[2]:
            idx[nm] = (round(c[0], 4), round(c[1], 4), rank)
    return idx

def main():
    idx = places()
    out, missing = [], []
    for code, name, short, typ, cap, fd, area, pop in R:
        ll = MANUAL.get(cap) or (idx[cap][:2] if cap in idx else None)
        if ll is None: missing.append(cap)
        out.append({'code': code, 'name': name, 'short': short, 'type': typ,
                    'capital': cap, 'capitalLL': list(ll) if ll else None,
                    'district': fd, 'area': area, 'pop': pop,
                    'note': NOTES.get(code)})
    print('subjects:', len(out), 'missing capitals:', missing)
    geo = json.load(open(os.path.join(SC, 'ru_regions_40.json')))
    have = {f['properties']['iso_3166_2'] for f in geo['features']}
    print('no geometry for:', [r['code'] for r in out if r['code'] not in have])
    print('no metadata for:', [c for c in have if c not in {r['code'] for r in out} and c != 'RU-X01~'])
    with open(os.path.join(SC, 'russia-regions.js'), 'w') as fh:
        fh.write('window.RU_REGIONS = ')
        json.dump(out, fh, ensure_ascii=False, indent=0)
        fh.write(';\n')

main()
