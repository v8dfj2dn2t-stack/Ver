// ---- Хелперы описания помещений ------------------------------------
function one(number, name, cat, w) {
  return { number: number || '', name, cat: cat || 'audience', w: w || 1 };
}
/** Последовательность аудиторий: seq(2053, 6) -> 2053, 2055, 2057... */
function seq(start, count, cat, opts = {}) {
  const step = opts.step === undefined ? 2 : opts.step;
  return Array.from({ length: count }, (_, i) => {
    const n = String(start + i * step);
    return {
      number: n,
      name: opts.name ? `${opts.name} ${n}` : `${CATEGORIES[cat || 'audience'].label} ${n}`,
      cat: cat || 'audience',
      w: opts.w || 1,
    };
  });
}
/** Помещения с буквенным префиксом: pre('ГЦ', 1, 6) -> ГЦ-01 … ГЦ-06 */
function pre(prefix, from, count, cat, opts = {}) {
  const step = opts.step || 1;
  return Array.from({ length: count }, (_, i) => {
    const num = `${prefix}-${String(from + i * step).padStart(2, '0')}`;
    return {
      number: num,
      name: opts.name ? `${opts.name} ${num}` : `${CATEGORIES[cat || 'service'].label} ${num}`,
      cat: cat || 'service',
      w: 1,
    };
  });
}

const stairs = (stack, label) => ({ number: '', name: label || 'Лестница', cat: 'stairs', w: 1, stack });
const elevator = (stack, label) => ({ number: '', name: label || 'Лифт', cat: 'elevator', w: 1, stack });
const entrance = (label) => ({ number: '', name: label || 'Вход', cat: 'entrance', w: 1, isEntrance: true });
/**
 * Переход в соседний корпус. По умолчанию стыкуется с переходом того же
 * этажа; если переход связывает разные отметки (как вход с улицы в
 * Новый корпус на 2-й этаж), обоим концам задаётся одинаковый key.
 */
const passage = (link, label, key) => ({ number: '', name: label, cat: 'passage', w: 1, link, key });

const maxSlots = sides => Math.max(
  (sides.a || []).reduce((s, r) => s + (r.w || 1), 0),
  (sides.b || []).reduce((s, r) => s + (r.w || 1), 0)
);

function block(id, axis, x, y, sides, slotsOverride) {
  const a = sides.a || [], b = sides.b || [];
  return { id, axis, x, y, slots: slotsOverride || maxSlots({ a, b }), a, b };
}

function floor(level, label, blocks, opts = {}) {
  return { level, label, blocks, note: opts.note || '' };
}

function building(id, code, name, about, numbering, floors) {
  return { id, code, name, about, numbering, floors };
}

// --- Этаж-«хребет»: продольный коридор с перпендикулярными крыльями ---
const SPINE_Y = 340;
const LEFT_X = 60;
const ARM_SLOTS = 4;

function spineFloor(level, label, parts, note) {
  const blocks = [];
  let x = LEFT_X;
  parts.forEach((part, i) => {
    if (part.run) {
      blocks.push(block(`run${i}`, 'h', x, SPINE_Y, part.run));
      x += maxSlots(part.run) * GEOM.SLOT;
      return;
    }
    const sides = part.armDown || part.armUp;
    const last = i === parts.length - 1;
    const connSlots = last ? ARM_SLOTS / 2 : ARM_SLOTS;
    const gap = connSlots * GEOM.SLOT;
    blocks.push(block(`conn${i}`, 'h', x, SPINE_Y, {}, connSlots));
    const ax = last ? x + gap : x + gap / 2;
    const len = maxSlots(sides) * GEOM.SLOT;
    const ay = part.armDown ? SPINE_Y + GEOM.CORRIDOR / 2 : SPINE_Y - GEOM.CORRIDOR / 2 - len;
    blocks.push(block(`arm${i}`, 'v', ax, ay, sides));
    x += gap;
  });
  return floor(level, label, blocks, { note });
}

const plainFloor = (level, label, sides, note) =>
  spineFloor(level, label, [{ run: sides }], note);

